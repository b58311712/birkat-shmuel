-- מטבח החסד - מיגרציה 46: תצוגת סעודה בממשק ההזמנות (סעיף 12.3)
-- =============================================================================
-- עד כה כל סעודה פעילה (is_active) הוצגה אוטומטית ללקוח בטופס ההזמנה, ולכן הדרך
-- היחידה להסתיר סעודה מהלקוח הייתה להשבית אותה לגמרי - מה שהוציא אותה גם
-- מהקטלוג, ממסלולי המחיר, מתיק השבת ומעריכת ההזמנה במשרד.
--
-- show_in_order_form מפריד בין השניים:
--   is_active          = false → הסעודה מושבתת בכל המערכת.
--   show_in_order_form = false → הסעודה פעילה לניהול פנימי (המשרד עדיין יכול
--                                לשבץ אותה בהזמנה), אך אינה מוצגת ללקוח בממשק
--                                ההזמנות. למשל סעודה שלישית עד שתיפתח להזמנה.
--
-- ברירת המחדל true שומרת על התנהגות זהה לכל הסעודות הקיימות.
-- =============================================================================

alter table meal_slots
  add column if not exists show_in_order_form boolean not null default true;

comment on column meal_slots.show_in_order_form is
  'true = הסעודה מוצגת ללקוח בממשק ההזמנות; false = פעילה לניהול פנימי בלבד (סעיף 12.3)';
