-- =============================================================================
-- מטבח החסד - מיגרציה 54: תמחור אירוע לפי עלות
-- =============================================================================
-- הזמנת שבת מתומחרת לפי מסלול מחיר (מחיר קבוע למנה לפי צירוף הסעודות שנבחר).
-- אירוע חריג אינו מתאים למודל הזה: הוא חד-פעמי, התפריט שלו לא סטנדרטי, ולכן
-- המחיר שלו נגזר מ**עלות המוצרים שנצרכו בפועל** כפול מספר המנות.
--
-- מקור העלות: inventory_items.last_purchase_price (מחיר בסיס לפני מע"מ, מיגרציה
-- 33), בתוספת מע"מ לפריט שאינו vat_exempt. החישוב עצמו ב-services/costing.js,
-- ועובר באותו מסלול המרת יחידות של ניכוי המלאי, כדי שהמחיר ישקף בדיוק את מה
-- שיורד מהמלאי.
-- =============================================================================

-- ----------------------------------------------------------------------------
-- שיטת התמחור של ההזמנה
-- ----------------------------------------------------------------------------
alter table orders
  add column pricing_mode           text not null default 'price_track',
  add column inventory_lines_amount numeric(10,2) not null default 0,
  add column base_amount_override   numeric(10,2);

alter table orders
  add constraint chk_orders_pricing_mode
    check (pricing_mode in ('price_track', 'cost_based'));

comment on column orders.pricing_mode is
  'price_track = מחיר למנה לפי מסלול (הזמנת שבת); cost_based = לפי עלות המוצרים (אירוע)';
comment on column orders.inventory_lines_amount is
  'סך שורות המלאי החופשיות בהזמנה (order_inventory_lines), מרכיב בסכום הסופי';
comment on column orders.base_amount_override is
  'תיקון ידני של מחיר הבסיס. null = הסכום המחושב. משמש כשהמנהל קובע מחיר אחר '
  'מהעלות המחושבת (למשל הכללת תקורה או עיגול לסכום נוח)';

-- ----------------------------------------------------------------------------
-- משלם שאינו אדם פרטי
-- ----------------------------------------------------------------------------
-- אירוע פנימי של הקהילה מחויב לגורם משלם שאינו חבר קהילה: ועד הקהילה, גבאי,
-- קרן, תורם. רשומת לקוח מתאימה למודל הגבייה, אך אסור שתופיע כלקוח רגיל ואסור
-- שתוכל להיכנס לממשק הלקוח. השם המלא נשמר ב-first_name (מיגרציה 43 עשתה את
-- full_name לעמודה מחושבת, ושם ארגון אינו מתפצל לפרטי/משפחה).
alter table customers
  add column is_organization boolean not null default false;

comment on column customers.is_organization is
  'true = גורם משלם שאינו אדם פרטי (ועד הקהילה, גבאי, קרן). לא מוצג ברשימת '
  'הלקוחות הרגילה ואינו נכנס לממשק הלקוח; משמש כמשלם של אירוע';

-- ----------------------------------------------------------------------------
-- סעודת ברירת המחדל של אירוע
-- ----------------------------------------------------------------------------
-- order_meals דורש meal_slot_id. אירוע אינו מחולק לליל שבת/בוקר, ולכן נזרעת
-- סעודת מערכת אחת בשם "אירוע". היא פעילה (המשרד יכול לשבץ אותה בהזמנה) אך
-- מוסתרת מטופס ההזמנה של הלקוח דרך show_in_order_form (מיגרציה 46).
--
-- אירוע רב-סעודתי (שבע ברכות ליומיים) עובד גם הוא, כי המנגנון תומך בכמה
-- סעודות לאותה הזמנה; זו רק ברירת המחדל.
insert into meal_slots (name, display_order, requires_companion, is_active, show_in_order_form)
select 'אירוע', 900, false, true, false
where not exists (select 1 from meal_slots where name = 'אירוע');
