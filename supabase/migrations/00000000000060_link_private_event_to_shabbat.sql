-- =============================================================================
-- מטבח החסד - מיגרציה 60: קישור אירוע פרטי לשבת קיימת
-- =============================================================================
-- עד כה כל אירוע (מיגרציה 52) יצר מועד עצמאי משלו (shabbatot בסוג 'event') עם
-- תיק עבודה נפרד. זה נכון לאירוע עצמאי לגמרי, אך שגוי לאירוע פרטי שחל בפועל
-- בזמן שבת קהילתית קיימת (למשל קידוש בר מצווה) - שם המנות הנוספות שייכות
-- לאותו מטבח, אותו ניכוי מלאי ואותה שבת, ולא לתיק עבודה מקביל שלא באמת מנוהל.
--
-- הפתרון: הזמנת אירוע פרטי מקושר אינה יוצרת shabbatot/shabbat_files חדשים
-- בכלל. היא מצביעה ישירות דרך orders.shabbat_id על השבת האמיתית הקיימת
-- (kind='shabbat'), עם pricing_mode='cost_based' בדיוק כמו אירוע עצמאי. שילוב
-- זה - pricing_mode='cost_based' על הזמנה ששייכת ל-shabbatot.kind='shabbat' -
-- הוא הזיהוי היחיד הדרוש ל"אירוע פרטי מקושר"; אין צורך בדגל נפרד.
--
-- מכיוון שרשומת המועד (shabbatot) משותפת עם השבת האמיתית, אי אפשר לשמור עליה
-- את שם/שעת האירוע הפרטי כפי שנעשה לאירוע עצמאי (זה היה "מזהם" את רשומת השבת
-- המשותפת עם כל שאר ההזמנות שלה). השדות עוברים להזמנה עצמה. הערות האירוע
-- המקושר נכתבות לעמודה הגנרית orders.notes (מיגרציה 48) שכבר קיימת ולא נוגעות
-- ב-shabbatot.notes המשותף.
-- =============================================================================

alter table orders
  add column event_title text,
  add column event_time  time;

comment on column orders.event_title is
  'שם אירוע פרטי שמקושר ישירות לשבת קיימת (pricing_mode=cost_based ו-shabbat_id '
  'מצביע על shabbatot.kind=shabbat). ריק בהזמנת שבת רגילה ובאירוע עצמאי - ששם '
  'שלו יושב על shabbatot.title (סעיף 60)';
comment on column orders.event_time is
  'שעת האירוע הפרטי המקושר, כשרלוונטי (סעיף 60)';
