מטבח החסד - ברכת שמואל$new$
where code = 'purchase_order_supplier'
  and body = $old$לכבוד {supplier_name},

להלן הזמנת רכש מספר {po_number} ממטבח החסד - ברכת שמואל.

הפריטים המבוקשים:
