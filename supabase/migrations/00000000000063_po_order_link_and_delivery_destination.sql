-- מטבח החסד - מיגרציה 63: קישור הזמנת רכש להזמנת לקוח + יעד אספקה לספק
-- =============================================================================
-- שלושה שינויים שמשלימים את שליחת הזמנת הרכש לספק (מיגרציה 61):
--
-- 1. purchase_orders.order_id - עד כה הזמנת רכש נקשרה למועד בלבד (shabbat_id),
--    ושבת אחת מכילה כמה הזמנות לקוח. כשהרכש נעשה עבור הזמנה מסוימת (למשל
--    אירוע פרטי, או רכש ישיר לאולם אחד) צריך לדעת לאיזו. הקישור מצומצם:
--    order_id מחייב שההזמנה תשב על אותו shabbat_id, והשרת מסנכרן את shabbat_id
--    מההזמנה שנבחרה, כדי שכל הלוגיקה הקיימת (דוח חוסרים, רכש ישיר, תיק שבת)
--    תמשיך לעבוד על המועד בדיוק כמו קודם.
--
-- 2. suppliers.delivery_destination - לאן הספק מספק. ברירת המחדל היא המטבח,
--    ויש ספקים (בעיקר ברכש ישיר) שמספקים ישירות לאולם האירוע. הערך יושב על
--    הספק ולא על ההזמנה כי זו תכונה קבועה של אופן העבודה מולו.
--
-- 3. system_settings.kitchen_address + {delivery_address} בנוסח לספק - כתובת
--    האספקה נכנסת למייל היוצא. הכתובת יושבת בהגדרות ולא בקוד כדי שניתן יהיה
--    לשנותה בלי דיפלוי.
-- =============================================================================

-- ----------------------------------------------------------------------------
-- 1. קישור הזמנת רכש להזמנת לקוח מסוימת
-- ----------------------------------------------------------------------------
alter table purchase_orders
  add column order_id uuid references orders(id) on delete set null;

create index idx_purchase_orders_order on purchase_orders (order_id);

comment on column purchase_orders.order_id is
  'הזמנת הלקוח שעבורה נעשה הרכש. אופציונלי: NULL = רכש למועד כולו או רכש שוטף. '
  'כשהשדה מלא, shabbat_id של הזמנת הרכש שווה תמיד ל-shabbat_id של ההזמנה.';

-- ----------------------------------------------------------------------------
-- 2. יעד אספקה בכרטיס הספק
-- ----------------------------------------------------------------------------
alter table suppliers
  add column delivery_destination text not null default 'kitchen';

alter table suppliers
  add constraint chk_suppliers_delivery_destination
  check (delivery_destination in ('kitchen', 'event_venue'));

comment on column suppliers.delivery_destination is
  'kitchen = אספקה למטבח החסד (ברירת מחדל, הכתובת מ-system_settings.kitchen_address); '
  'event_venue = אספקה למקום האירוע, לפי האולם של הזמנת הלקוח המקושרת להזמנת הרכש. '
  'ספק כזה בלי הזמנת לקוח מקושרת נופל חזרה לכתובת המטבח.';

-- ----------------------------------------------------------------------------
-- 3. כתובת המטבח כהגדרת מערכת
-- ----------------------------------------------------------------------------
insert into system_settings (key, value, description) values
  ('kitchen_address', '"רח׳ החוזה מלובלין 1, ביתר עילית"',
    'כתובת מטבח החסד - יעד האספקה שנשלח לספקים שאינם מספקים ישירות לאולם')
on conflict (key) do nothing;

-- ----------------------------------------------------------------------------
-- 4. {delivery_address} בנוסח המייל לספק
-- ----------------------------------------------------------------------------
-- הנוסח ניתן לעריכה ע"י המנהלת, ולכן מתעדכן כאן *רק* אם הוא עדיין זהה בדיוק
-- לברירת המחדל של מיגרציה 61. נוסח שנערך נשאר כפי שהוא, והמנהלת יכולה להוסיף
-- את ה-placeholder בעצמה במסך ניהול המיילים.
