-- =============================================================================
-- מטבח החסד - מיגרציה 57: חישוב כמות הכנה מעוגלת בנפרד לכל סעודה
-- =============================================================================
-- בקטגוריות מסוימות (למשל סלטים, שנקבעות ב-0.04 ליטר/ק"ג לסועד) כמות ההכנה
-- בדוח המטבח (סעיף 21) צריכה להיחשב לכל סעודה בנפרד (מנות הסעודה * כמות-למנה)
-- ולעגל כל סעודה בנפרד לחצי הקרוב - ולא לסכם את כל מנות השבת מכל הסעודות
-- ולעגל כלפי מעלה פעם אחת כמו בשאר הקטגוריות (העיגול הכללי, סעיף 21.4).
--
--   categories.round_prep_by_slot - דגל: כמות ההכנה המעוגלת בדוח המטבח מחושבת
--     בנפרד לכל סעודה ומעוגלת לחצי הקרוב, ואז מסוכמת. ברירת מחדל: כבוי (עיגול
--     כלפי מעלה על סך מנות השבת, כרגיל).
-- =============================================================================

alter table categories
  add column if not exists round_prep_by_slot boolean not null default false;

comment on column categories.round_prep_by_slot is
  'true = כמות ההכנה בדוח המטבח מחושבת בנפרד לכל סעודה (מנות הסעודה * כמות-למנה) ומעוגלת לחצי הקרוב, ואז מסוכמת - במקום עיגול כלפי מעלה על סך מנות השבת.';

update categories
set round_prep_by_slot = true
where name in ('סלטים', 'סלטים קבועים');
